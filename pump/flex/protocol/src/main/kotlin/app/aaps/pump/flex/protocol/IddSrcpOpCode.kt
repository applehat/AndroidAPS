package app.aaps.pump.flex.protocol

/**
 * Status Reader Control Point opcodes (16-bit, little-endian on the wire).
 *
 * Recovered from MiniMed Instinct US 1.3.1 (`IddSrcpOpCode`). Request/response pairs.
 * Not every member is exercised by the AAPS driver skeleton; listed for completeness so
 * hardware bring-up has the full map.
 */
enum class IddSrcpOpCode(val wire: Int) {
    RESPONSE(0x303),
    RESET_STATUS(0x30C),
    GET_ACTIVE_BOLUS_IDS(0x330),
    GET_ACTIVE_BOLUS_IDS_RESPONSE(0x33F),
    GET_ACTIVE_BOLUS_DELIVERY(0x356),
    GET_ACTIVE_BOLUS_DELIVERY_RESPONSE(0x359),
    BASAL_RATE_DELIVERY(0x365),
    BASAL_RATE_DELIVERY_RESPONSE(0x36A),
    GET_SENSOR_ESA_DURATION(0x3C0),
    GET_SENSOR_ESA_DURATION_RESPONSE(0x3CF),
    INSULIN_ON_BOARD(0x3F3),
    INSULIN_ON_BOARD_RESPONSE(0x3FC),
    GET_BG_REQUEST_DETAILS_REQUEST(0x3FD),
    GET_BG_REQUEST_DETAILS_RESPONSE(0x3FE),
    GET_SENSOR_SESSION_START_TIME(0x407),
    GET_SENSOR_SESSION_START_TIME_RESPONSE(0x408),
    GET_SENSOR_STATUS(0x409),
    GET_SENSOR_STATUS_RESPONSE(0x40A),
    GET_NEXT_SENSOR_CAL_TIME(0x40B),
    GET_NEXT_SENSOR_CAL_TIME_RESPONSE(0x40C),
    GET_SENSOR_END_OF_LIFE_TIME(0x40F),
    GET_SENSOR_END_OF_LIFE_TIME_RESPONSE(0x410),
    GET_SENSOR_DEVICE_INFO(0x411),
    GET_SENSOR_DEVICE_INFO_RESPONSE(0x412),
    GET_SENSOR_WARMUP_TIME_REMAINING(0x413),
    GET_SENSOR_WARMUP_TIME_REMAINING_RESPONSE(0x414),
    GET_ACTIVE_ALGORITHM_PROGRESS_TYPES(0x417),
    GET_ACTIVE_ALGORITHM_PROGRESS_TYPES_RESPONSE(0x418),
    GET_ALGORITHM_PROGRESS(0x419),
    GET_ALGORITHM_PROGRESS_RESPONSE(0x41A),
    GET_LAST_CGM_CALIBRATION_RESULT(0x41B),
    GET_LAST_CGM_CALIBRATION_RESULT_RESPONSE(0x41C),
    GET_ALERT_STACK(0x41D),
    GET_ALERT_STACK_RESPONSE(0x41E),
    GET_INFUSION_SETUP_STATUS(0x41F),
    GET_INFUSION_SETUP_STATUS_RESPONSE(0x420),
    GET_ACTIVE_ALGORITHM_STATUS_TYPES(0x421),
    GET_ACTIVE_ALGORITHM_STATUS_TYPES_RESPONSE(0x422),
    GET_ALGORITHM_STATUS(0x423),
    GET_ALGORITHM_STATUS_RESPONSE_V2(0x426),
    GET_LAST_BG_CHECK_STATUS(0x427),
    GET_LAST_BG_CHECK_STATUS_RESPONSE(0x428);

    companion object {
        fun fromWire(value: Int): IddSrcpOpCode? = entries.firstOrNull { it.wire == value }
    }
}
